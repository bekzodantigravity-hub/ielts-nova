export function translateGoal(rawGoal: string | undefined, lang: Lang): string {
  if (!rawGoal) return DICT[lang].auth.goalStudyAbroad;
  const g = rawGoal.toLowerCase();
  if (
    g.includes("chet elda") ||
    g.includes("рубежом") ||
    g.includes("international study") ||
    g.includes("study_abroad")
  ) {
    return DICT[lang].auth.goalStudyAbroad;
  }
  if (
    g.includes("migratsiya") ||
    g.includes("релокация") ||
    g.includes("skilled migration") ||
    g.includes("work_migration")
  ) {
    return DICT[lang].auth.goalWorkMigration;
  }
  if (
    g.includes("ilmiy") ||
    g.includes("oliygoh") ||
    g.includes("наука") ||
    g.includes("postgraduate") ||
    g.includes("local_uni")
  ) {
    return DICT[lang].auth.goalLocalUni;
  }
  if (
    g.includes("karyera") ||
    g.includes("профессиональный") ||
    g.includes("career advancement") ||
    g.includes("career_growth")
  ) {
    return DICT[lang].auth.goalCareerGrowth;
  }
  return rawGoal;
}
